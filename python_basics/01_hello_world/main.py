def demonstrate_f_strings():
    """Демонстрация f-строк (formatted string literals)."""
    print("\n" + "=" * 50)
    print("📌 F-СТРОКИ (Python 3.6+)")
    print("=" * 50)

    name = "Анна"
    age = 25
    height = 1.68

    # f-строки позволяют вставлять переменные прямо в строку
    print(f"Привет, меня зовут {name}!")
    print(f"Мне {age} лет.")

    # Внутри {} можно писать выражения
    print(f"Через 5 лет мне будет {age + 5} лет.")
    print(f"Мой рост в сантиметрах: {height * 100:.0f} см")

    # Форматирование чисел
    price = 1499.99
    print(f"Цена: {price:.2f} руб.")  # Два знака после запятой

    # Старый способ (до Python 3.6) — метод .format()
    print("Старый способ: Меня зовут {}. Мне {} лет.".format(name, age))


