def demonstrate_print():
    """Демонстрация всех возможностей функции print()."""
    print("=" * 50)
    print("📌 ДЕМОНСТРАЦИЯ ФУНКЦИИ print()")
    print("=" * 50)

    # 1. Простой вывод строки
    print("1. Привет, Мир!")

    # 2. Вывод числа
    print("2.", 42)

    # 3. Вывод нескольких аргументов (автоматически разделяются пробелом)
    print("3.", "Python", "это", "круто!")

    # 4. Параметр sep — разделитель между аргументами
    print("4.", "a", "b", "c", sep=" → ")  # Вывод: a → b → c
    print("4.", "192", "168", "0", "1", sep=".")  # Вывод: 192.168.0.1

    # 5. Параметр end — что печатать в конце (по умолчанию \n — перевод строки)
    print("5. Первая строка", end=" ... ")
    print("Вторая строка (на той же строке!)")

    # 6. Пустой print() — просто перевод строки
    print()
    print("6. Выше была пустая строка")

    # 7. Спецсимволы в строках
    print("7. Первая строка\nВторая строка")  # \n — перевод строки
    print("7. Колонка1\tКолонка2\tКолонка3")  # \t — табуляция
    print('7. Одинарные кавычки тоже работают')
    print("7. А в двойных можно 'одинарные' без экранирования")


def demonstrate_input():
    """Демонстрация работы с функцией input()."""
    print("\n" + "=" * 50)
    print("📌 ДЕМОНСТРАЦИЯ ФУНКЦИИ input()")
    print("=" * 50)

    # input() всегда возвращает строку (str)
    name = input("👤 Введите ваше имя: ")
    print(f"Привет, {name}! Добро пожаловать в Python! 🎉")

    # Важно: input() возвращает строку, даже если ввели число!
    age_str = input("🎂 Введите ваш возраст: ")
    print(f"Тип данных age_str: {type(age_str)}")  # <class 'str'>

    # Преобразование строки в число
    age = int(age_str)  # int() преобразует строку в целое число
    print(f"Через 10 лет вам будет: {age + 10} лет")


