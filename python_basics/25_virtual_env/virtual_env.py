def what_is_venv():
    """
    Виртуальное окружение — изолированная среда Python для конкретного проекта.

    ПРОБЛЕМА:
      Проект А требует requests==2.20.0
      Проект Б требует requests==2.28.0
      Глобальная установка не может иметь обе версии одновременно.

    РЕШЕНИЕ:
      Каждый проект имеет своё виртуальное окружение
      со своими зависимостями и версией Python.

    Аналогия:
      Глобальный Python — общежитие (все вместе)
      venv — отдельная квартира для проекта (изоляция)
    """
    print("=" * 60)
    print("1. ЗАЧЕМ НУЖНЫ ВИРТУАЛЬНЫЕ ОКРУЖЕНИЯ?")
    print("=" * 60)

    print("Проблема: конфликт версий зависимостей между проектами")
    print("Решение: изолированное окружение для каждого проекта")
    print()

    # Показать текущий Python и окружение
    print(f"Текущий Python: {sys.executable}")
    print(f"Версия: {sys.version}")
    print(f"В виртуальном окружении: {sys.prefix != sys.base_prefix}")

    # Показать site-packages
    for path in sys.path:
        if "site-packages" in path:
            print(f"Site-packages: {path}")


